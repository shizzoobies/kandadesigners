import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { serveDist } from './lib/serve-dist.mjs';
const require = createRequire('file:///D:/kap-reel/node_modules/');
const { chromium } = require('playwright');
const browser = await chromium.launch();
const server = await serveDist('public');
const report = { checks: [], errors: [], note: 'In-app browser reconnection returned No browser is available. Existing local Playwright used for follow-up regression checks.' };
const out = 'docs/training-upgrades/finance-qa';
await mkdir(out, { recursive: true });
const check = (condition, label) => {
  report.checks.push({ label, passed: Boolean(condition) });
  if (!condition) throw new Error(label);
};
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
  page.on('pageerror', error => report.errors.push(error.message));
  page.setDefaultTimeout(7000);
  await page.goto(server.origin + '/training-samples/finance/');
  check(await page.locator('.brand-logo').getAttribute('src') === 'assets/img/ka-logo.webp', 'Logo reference is local to the package');
  check(await page.locator('.brand-logo').evaluate(i => i.complete && i.naturalWidth > 0), 'Packaged logo loads');
  let failAudio = true;
  await page.route('**/assets/audio/screen-1.mp3', route => failAudio ? route.fulfill({ status: 503, body: '' }) : route.continue());
  await page.getByRole('button', { name: 'Listen to this lesson', exact: true }).click();
  await page.getByRole('button', { name: 'Retry audio', exact: true }).waitFor();
  check((await page.locator('#audio-status').textContent()).includes('unavailable'), 'Media error label survives pause events');
  failAudio = false;
  await page.getByRole('button', { name: 'Retry audio', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('audio').paused && document.querySelector('audio').currentTime > 0);
  check(await page.locator('.audio-dock').evaluate(el => el.classList.contains('is-playing')), 'Retry recovers actual playback and guide signal');
  await page.getByRole('button', { name: 'Pause introduction', exact: true }).click();
  check(!(await page.locator('.audio-dock').evaluate(el => el.classList.contains('is-playing'))), 'Guide stops on pause');
  await page.getByRole('button', { name: 'Mute narration', exact: true }).click();
  check(await page.locator('audio').evaluate(el => el.muted), 'Custom mute changes media state');
  await page.getByRole('button', { name: 'Unmute narration', exact: true }).click();
  check(!(await page.locator('audio').evaluate(el => el.muted)), 'Custom unmute changes media state');
  await page.locator('#audio-seek').fill('50');
  await page.waitForFunction(() => Math.abs(document.querySelector('audio').currentTime - document.querySelector('audio').duration / 2) < 1);
  check(await page.locator('audio').evaluate(el => Math.abs(el.currentTime - el.duration / 2) < 1), 'Custom seek updates media position');
  check(!(await page.locator('audio').evaluate(el => el.controls)), 'Native audio controls removed');
  check(await page.locator('.guide-signal').evaluate(el => getComputedStyle(el).animationName === 'none'), 'Reduced motion disables guide animation');
  await page.screenshot({ path: out + '/finance-1280-custom-audio.png' });
  await page.setViewportSize({ width: 360, height: 800 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Custom controls fit phone width');
  check(await page.evaluate(() => document.querySelector('main').getBoundingClientRect().bottom <= document.querySelector('.audio-dock').getBoundingClientRect().top + 1), 'Open transcript reserves phone layout space');
  await page.screenshot({ path: out + '/finance-360-custom-audio.png' });
  await page.getByRole('button', { name: 'Fold transcript', exact: true }).click();
  await page.getByRole('button', { name: 'Open the ledger', exact: true }).click();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByRole('button', { name: 'Net income $4,100', exact: true }).click();
  for (let i = 0; i < 6; i++) await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Gross margin percent', exact: true }).fill('60');
  await page.getByRole('button', { name: 'Check calculation', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Gross margin percent', exact: true }).fill('40');
  check((await page.locator('#read-feedback').textContent()).includes('Check it again'), 'Editing an answer invalidates checked feedback');
  await page.getByRole('button', { name: 'Finish review', exact: true }).click();
  check((await page.locator('#done-results').textContent()).includes('Calculations correct: 0 of 3'), 'Edited answer cannot retain a stale correct score');
  await page.getByRole('button', { name: 'Start a fresh review', exact: true }).click();
  await page.getByRole('button', { name: 'Open the ledger', exact: true }).click();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  check(await page.getByRole('button', { name: 'Revenue $80,000', exact: true }).getAttribute('aria-pressed') === 'true', 'Restart restores the first ledger line');
  check(report.errors.length === 0, 'No JavaScript errors');
} finally {
  await writeFile(out + '/followup-checks.json', JSON.stringify(report, null, 2));
  await browser.close();
  await server.close();
}
